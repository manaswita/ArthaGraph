export function generateChartBars(cmp: number, atr: number, days = 20) {
  const dates: string[] = [];
  const prices: number[] = [];
  const ema20: number[] = [];
  const ema50: number[] = [];
  const volumes: number[] = [];

  let currentPrice = cmp * 0.94;
  let runningEma20 = currentPrice * 0.98;
  let runningEma50 = currentPrice * 0.96;

  const now = new Date();

  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    dates.push(d.toLocaleDateString('en-IN', { month: 'short', day: 'numeric' }));

    // Slight upward drift with realistic noise
    const delta = (Math.random() - 0.42) * (atr * 0.65);
    currentPrice = i === 0 ? cmp : Math.max(cmp * 0.85, currentPrice + delta);
    prices.push(Math.round(currentPrice * 10) / 10);

    runningEma20 = runningEma20 * 0.85 + currentPrice * 0.15;
    runningEma50 = runningEma50 * 0.92 + currentPrice * 0.08;
    ema20.push(Math.round(runningEma20 * 10) / 10);
    ema50.push(Math.round(runningEma50 * 10) / 10);

    const vol = Math.floor((Math.random() * 0.8 + 0.6) * (i < 3 ? 1.9 : 1.0) * 1000000);
    volumes.push(vol);
  }

  return { dates, prices, ema20, ema50, volumes };
}
